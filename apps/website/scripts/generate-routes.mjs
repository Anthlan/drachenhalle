import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import config from "../src/i18n/config.json" with { type: "json" };
import { contentPath } from "./content-files.mjs";

const siteRoot=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const repositoryRoot=path.resolve(siteRoot,"../..");
const dataRoot=path.join(siteRoot,"src","data");
const outputPath=path.join(siteRoot,"src","i18n","content-routes.generated.mjs");
const areaPaths={
  docs:{de:"docs",en:"guides",fr:"guides",ru:"руководства",pt:"guias"},
  news:{de:"neuigkeiten",en:"news",fr:"actualites",ru:"новости",pt:"noticias"},
  calendar:{de:"termine",en:"calendar",fr:"calendrier",ru:"календарь",pt:"calendario"},
};

const slugify=value=>value.normalize("NFKD").replace(/[\u0300-\u036f]/g,"").toLocaleLowerCase()
  .replace(/[^\p{L}\p{N}]+/gu,"-").replace(/^-|-$/g,"").slice(0,96);
const stripFrontmatter=source=>source.replace(/^\uFEFF/,"").replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n/,"");
const metadataTitle=source=>source.match(/^title:\s*["']?(.*?)["']?\s*$/m)?.[1];
const headingTitle=source=>stripFrontmatter(source).match(/^#\s+(.+)$/m)?.[1]
  ?.replace(/[`*_~]/g,"").replace(/^\p{Emoji_Presentation}\s*/u,"").trim();
const localizedTitle=async(source,language,fallback)=> {
  const file=contentPath(path.join(repositoryRoot,...source.split("/")),language);
  try { const text=await readFile(file,"utf8");return metadataTitle(text)??headingTitle(text)??fallback; }
  catch { return fallback; }
};
const routePath=(area,language,slug)=>`/${areaPaths[area][language]}/${slug}/`;

const docs=JSON.parse(await readFile(path.join(dataRoot,"docs.generated.json"),"utf8")).items.filter(item=>!item.hidden);
const news=JSON.parse(await readFile(path.join(dataRoot,"news.generated.json"),"utf8")).items;
const events=JSON.parse(await readFile(path.join(dataRoot,"events.generated.json"),"utf8")).items;
const definitions=[
  ...docs.map(item=>({area:"docs",item})),
  ...news.map(item=>({area:"news",item})),
  ...events.map(item=>({area:"calendar",item})),
];
const routes=[];
for(const {area,item} of definitions) {
  const paths={de:item.url?.slice(config.base.length)??item.detailUrl.slice(config.base.length)};
  for(const language of config.languages.filter(({code})=>code!==config.defaultLanguage)) {
    const title=await localizedTitle(item.source,language.code,item.title);
    const slug=(area==="calendar"?`${item.date}-`:"")+slugify(title);
    paths[language.code]=routePath(area,language.code,slug||item.slug);
  }
  routes.push({id:`content:${item.source}`,paths});
}
for(const language of config.languages) {
  const seen=new Map();
  for(const route of routes) {
    const key=route.paths[language.code];
    if(seen.has(key))throw new Error(`Duplicate ${language.code} route ${key}: ${seen.get(key)} and ${route.id}`);
    seen.set(key,route.id);
  }
}
await writeFile(outputPath,`// Generated by scripts/generate-routes.mjs.\nexport default ${JSON.stringify(routes,null,2)};\n`,"utf8");
console.log(`Generated ${routes.length} localized content routes.`);
